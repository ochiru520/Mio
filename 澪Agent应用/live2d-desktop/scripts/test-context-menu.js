const assert = require('assert')
const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '../..')
const html = fs.readFileSync(path.join(root, 'public/live2d-pet/index.html'), 'utf8')
const actions = [...html.matchAll(/data-action="([^"]+)"/g)].map((match) => match[1])

assert.deepStrictEqual(actions, ['chat', 'size', 'speech-language', 'speech-bubble', 'agent', 'close'])
assert.match(html, />打开\/关闭对话窗口</)
assert.match(html, />打开 Mio</)
assert.match(html, />语音语言：中文</)

const renderer = fs.readFileSync(path.join(root, 'public/live2d-pet/live2d-pet.js'), 'utf8')
assert.match(renderer, /speechLanguage \|\| message\.speech_language \|\| \(settings\.pet_speech_language === 'ja' \? 'ja' : 'zh'\)/)
assert.match(renderer, /beginVoiceLifecycle\(message, text, mode/)
assert.match(renderer, /function showSpeechBubble\(text, durationMs = 0, responseId = ''\)/)
assert.match(renderer, /showSpeechBubble\(text, 0, messageResponseId\(payload\)\)/)
assert.match(renderer, /const text = chunks\.join\('\\n'\)/)
assert.doesNotMatch(renderer, /chinese-timeout-fallback/)
assert.match(renderer, /日语语音未能在 12 秒内开始，已停止；不会改说中文/)
assert.match(renderer, /showSpeechBubble\(lastSpeechError, 0, messageResponseId\(message\)\)/)
assert.match(renderer, /if \(priority <= activeSpeechPriority\) return enqueueSpeech/)
assert.match(renderer, /streamPendingDuration >= 0\.28/)
assert.match(renderer, /format\.sampleRate \* 0\.16/)
assert.match(renderer, /speechFinishedCount/)
assert.match(renderer, /rendererFps/)
assert.match(renderer, /speakingMotion !== idleMotion/)
assert.match(renderer, /speechDroppedCount/)
assert.match(renderer, /speechFailureCount/)
assert.match(renderer, /speechLifecycleHistory/)
assert.match(renderer, /resetSpeechDiagnostics/)
assert.match(renderer, /frameTimeP95Ms/)
assert.match(renderer, /framesOver33Ms/)
assert.match(renderer, /framesOver50Ms/)
assert.match(renderer, /options\?\.includePixels/)

console.log(JSON.stringify({ ok: true, contextMenuActions: actions }, null, 2))
