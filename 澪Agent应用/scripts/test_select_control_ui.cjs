    measured.menu=await page.getByRole('listbox').evaluate(el=>{const s=getComputedStyle(el);return{fontSize:parseFloat(getComputedStyle(el.firstElementChild).fontSize),radius:parseFloat(s.borderRadius),padding:parseFloat(s.paddingTop),border:parseFloat(s.borderTopWidth),itemRadius:parseFloat(getComputedStyle(el.firstElementChild).borderRadius)}})
