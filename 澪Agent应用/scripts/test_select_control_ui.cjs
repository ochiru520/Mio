  assert.equal(await page.evaluate(()=>window.selectControlFixture.state.number),1)
  await grouped.click()
  assert.equal(await page.getByRole('option',{name:'禁用分组：四',exact:true}).getAttribute('aria-disabled'),'true')
  await page.getByRole('option',{name:'禁用分组：四',exact:true}).click({force:true})
  assert.equal(await page.evaluate(()=>window.selectControlFixture.state.number),1)
  await grouped.press('Escape')
  checks.push('分组以中文冒号区分、禁用组不可选，number modifier保留数字类型')
