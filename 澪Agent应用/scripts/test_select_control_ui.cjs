    const measured=await primary.evaluate(el=>{const r=el.getBoundingClientRect(),s=el.querySelector('span').getBoundingClientRect();return{fontSize:parseFloat(getComputedStyle(el).fontSize),arrowCount:el.querySelectorAll('svg').length,rightPadding:r.right-s.right,expanded:el.getAttribute('aria-expanded')}})
