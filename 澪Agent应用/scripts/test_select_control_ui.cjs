    assert.equal(measured.menu.radius-measured.menu.padding-measured.menu.border,measured.menu.itemRadius)
    const box=await page.getByRole('listbox').boundingBox();assert(box.x>=0&&box.x+box.width<=width)
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))
